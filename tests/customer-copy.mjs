import assert from 'node:assert/strict';
import { neutralCustomerResponse, neutralCustomerText } from '../.copy-test/customerCopy.js';
const source = {name:'上游商品', message:'上游供应商配置失败', nested:{lastError:'金山云返回错误'}, configOptions:[{id:'上游原始ID',value:'上游原始值',displayValue:'上游规格'}], url:'https://example.com/上游',token:'上游token'};
const result=neutralCustomerResponse(source);
assert.equal(result.name,'资源商品');
assert.equal(result.message,'平台配置失败');
assert.equal(result.nested.lastError,'平台返回错误');
assert.equal(result.configOptions[0].displayValue,'资源规格');
assert.equal(result.configOptions[0].id,source.configOptions[0].id);
assert.equal(result.configOptions[0].value,source.configOptions[0].value);
assert.equal(result.url,source.url);
assert.equal(result.token,source.token);
assert.equal(source.name,'上游商品');
assert.equal(neutralCustomerText('普通提示'),'普通提示');
console.log('customer copy: display normalized; protocol ids/values/URLs/tokens and source unchanged');
const download=new Blob(['上游binary']);
assert.equal(neutralCustomerResponse(download),download);
const buffer=new ArrayBuffer(4);
assert.equal(neutralCustomerResponse(buffer),buffer);
